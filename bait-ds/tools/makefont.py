# Renders Press Start 2P (SIL OFL) at 8px into an 8x8 1-bit font table for ASCII 32..126.
import sys
from PIL import Image, ImageDraw, ImageFont
ttf, out = sys.argv[1], sys.argv[2]
font = ImageFont.truetype(ttf, 8)
rows = []
for code in range(32, 127):
    im = Image.new('L', (8, 8), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    bits = []
    for y in range(8):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 127:
                b |= 0x80 >> x
        bits.append(b)
    rows.append(bits)
with open(out, 'w') as f:
    f.write('// Generated by tools/makefont.py from Press Start 2P (SIL Open Font License).\n')
    f.write('#pragma once\n#include <nds/ndstypes.h>\n')
    f.write('static const u8 FONT8[95][8] = {\n')
    for code, bits in zip(range(32, 127), rows):
        f.write('  {' + ','.join('0x%02x' % b for b in bits) + '}, // ' + repr(chr(code)) + '\n')
    f.write('};\n')
